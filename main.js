  // Sticky Navbar
  $(window).scroll(function () {
    if ($(this).scrollTop() > 40) {
      $(".navbar").addClass("sticky-top");
    } else {
      $(".navbar").removeClass("sticky-top");
    }
  });

  // Custom Active Link Handling (Replacement for ScrollSpy)
  $(window).scroll(function () {
    var scrollDistance = $(window).scrollTop() + 100; // Add offset for fixed navbar

    // Assign active class to nav links while scrolling
    $('.navbar-nav .nav-link[href^="#"]').each(function (i) {
      var target = $(this.hash);
      if (target.length) {
        if (
          target.offset().top <= scrollDistance &&
          target.offset().top + target.outerHeight() > scrollDistance
        ) {
          $(".navbar-nav .nav-link").removeClass("active");
          $(this).addClass("active");
        }
      }
    });

    // Handle case when at the very top (optional backup)
    if ($(window).scrollTop() < 10) {
      $('.navbar-nav .nav-link[href="#home"]').addClass("active");
    }
  });

  // Close navbar on click for mobile
  $(".navbar-nav .nav-link:not(.dropdown-toggle), .navbar-collapse .btn").on(
    "click",
    function () {
      $(".navbar-collapse").collapse("hide");
    },
  );

